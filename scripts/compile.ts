import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import solc from 'solc';
export function compileIdentity() {
  const out = JSON.parse(solc.compile(JSON.stringify({language:'Solidity',sources:{'RomeIdentityManager.sol':{content:readFileSync(new URL('../contracts/RomeIdentityManager.sol',import.meta.url),'utf8')}},settings:{evmVersion:'paris',optimizer:{enabled:true,runs:200},outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object']}}}})));
  if(out.errors?.some((e:any)=>e.severity==='error')) throw new Error(JSON.stringify(out.errors));
  const c=out.contracts['RomeIdentityManager.sol'].RomeIdentityManager;
  return {abi:c.abi,bytecode:`0x${c.evm.bytecode.object}` as `0x${string}`,compiler:solc.version(),evmVersion:'paris'};
}
if (process.argv[1] && import.meta.url===pathToFileURL(process.argv[1]).href) {
  const artifact=compileIdentity(); mkdirSync('artifacts',{recursive:true});
  writeFileSync('artifacts/RomeIdentityManager.json',JSON.stringify(artifact,null,2));
  writeFileSync('lib/rome/abi.ts',`// Generated by npm run compile.\nexport const identityAbi = ${JSON.stringify(artifact.abi,null,2)} as const;\n`);
  console.log(`Compiled RomeIdentityManager: ${(artifact.bytecode.length-2)/2} deployment bytes; ${artifact.compiler}; paris`);
}
